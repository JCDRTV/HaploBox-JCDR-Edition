dofile("distribution/team-rebuild/Planning.lua")
local db={}
local m=assert(HaploBoxPlanning.New(db))
local function character(n,a,g)
    return {name=n,realm="Forever PvE",account=a,race="NightElf",class="DRUID",level=27,guid=g}
end
local function no(a,b) assert(a==nil and type(b)=="string",tostring(b)) end
local a=assert(m.SaveCharacter(character("Mael Ashgrove","WoW1","Player-1")))
local b=assert(m.SaveCharacter(character("Lyra Ashgrove","WoW2")))
local c=assert(m.SaveCharacter(character("Elya Ashgrove","WoW3")))
local d=assert(m.SaveCharacter(character("Nyra Ashgrove","WoW4")))
local e=assert(m.SaveCharacter(character("Ayla Ashgrove","WoW5")))
local other=assert(m.SaveCharacter(character("Other","WoW1")))
no(m.SaveCharacter(character("mael ashgrove","WoW9")))
local normalized=character("mael ashgrove","WoW1","Player-1")
normalized.realm="ForeverPvE"
assert(m.SaveCharacter(normalized).id==a.id)
local conflict=character("Mael Ashgrove","WoW1","Player-9")
no(m.SaveCharacter(conflict))
local update=character("Lyra Ashgrove","WoW2","Player-2")
update.level=28
assert(m.SaveCharacter(update).id==b.id)
assert(m.GetCharacter(b.id).level==28)
assert(#m.GetCharacters()==6)
local function s(c,r) return {characterId=c.id,role=r or "DPS"} end
no(m.SaveTeam("single",{s(a)}))
no(m.SaveTeam("duplicate",{s(a),s(a)}))
no(m.SaveTeam("same account",{s(a),s(other)}))
no(m.SaveTeam("bad role",{s(a,"INVALID"),s(b)}))
no(m.SaveTeam("invalid pos",{[1]=s(a),[6]=s(b)}))
no(m.SaveTeam("unknown",{s(a),{characterId="missing",role="DPS"}}))
local draft={[1]=s(a,"TANK"),[3]=s(b,"HEALER"),[5]=s(c)}
local t=assert(m.SaveTeam("Team A",draft))
assert(m.GetActiveTeam()==nil)
assert(m.SetActiveTeam(t.id).id==t.id)
local members=m.GetOrderedMembers()
assert(#members==3 and members[1].pos==1 and members[2].pos==3 and members[3].pos==5)
assert(members[2].role=="HEALER")
draft[1]=s(e)
assert(m.GetTeam(t.id).slots[1].characterId==a.id)
members[1].character.name="mutated"
assert(m.GetCharacter(a.id).name~="mutated")
no(m.SaveTeam("team a",{s(a),s(b)}))
no(m.RemoveCharacter(a.id))
local change=character("Lyra Ashgrove","WoW1","Player-2")
no(m.SaveCharacter(change,b.id))
local full={s(e),s(d,"TANK"),s(c),s(b,"HEALER"),s(a)}
assert(m.SaveTeam("Team A",full,t.id).id==t.id)
assert(m.GetOrderedMembers()[1].character.id==e.id)
assert(m.GetOrderedMembers()[2].role=="TANK")
local second=assert(m.SaveTeam("Duo",{[2]=s(b),[4]=s(d)}))
assert(m.GetActiveTeam().id==t.id)
assert(m.SetActiveTeam(second.id))
local reload=assert(HaploBoxPlanning.New(db))
assert(reload.GetActiveTeam().id==second.id)
assert(reload.GetOrderedMembers()[1].pos==2)
assert(reload.GetOrderedMembers()[2].pos==4)
assert(#reload.GetTeams()==2)
assert(reload.ClearActiveTeam())
assert(reload.GetActiveTeam()==nil and #reload.GetOrderedMembers()==0)
assert(reload.RemoveCharacter(other.id))
assert(#reload.GetCharacters()==5)
no(HaploBoxPlanning.New({schema=99}))
print("PASS: character identity, duplicates, account validation, roles, positions, 2-5 members, persistence, active team and safe copy")
